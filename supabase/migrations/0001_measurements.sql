-- Tabela de medições do sensor ESP32 + PZEM-004T.
-- Espelha a tabela "measurements" de produção (colunas lidas pelo painel de
-- Sensores e gravadas pela função netlify/functions/sensor.js).
-- Rode no SQL Editor do projeto Supabase de DESENVOLVIMENTO.

create table if not exists public.measurements (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  sensor_id text not null,
  voltage double precision,              -- V
  current double precision,              -- A
  power double precision,                -- W (o PZEM envia watts)
  power_factor double precision,         -- 0 a 1
  estimated_monthly_cost double precision
);

create index if not exists measurements_sensor_time_idx
  on public.measurements (sensor_id, created_at desc);

-- Acesso pelo navegador (chave publishable/anon).
alter table public.measurements enable row level security;

-- O painel lê as medições.
drop policy if exists "leitura publica das medicoes" on public.measurements;
create policy "leitura publica das medicoes"
  on public.measurements for select
  to anon, authenticated
  using (true);

-- SÓ NO BANCO DE TESTES: permite gravar com a chave pública para simular o
-- sensor sem o ESP32. Em produção a gravação deve vir só do dispositivo/função
-- (item "supabase-rls" do checklist).
drop policy if exists "dev: gravacao de teste" on public.measurements;
create policy "dev: gravacao de teste"
  on public.measurements for insert
  to anon
  with check (true);

-- Atualização ao vivo no painel (Supabase Realtime).
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'measurements'
  ) then
    alter publication supabase_realtime add table public.measurements;
  end if;
end $$;
